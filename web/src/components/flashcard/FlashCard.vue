<template>
  <div class="card border-0 shadow-sm h-100 hoverable">
    <div class="card-body">
      <div class="d-flex justify-content-between align-items-start mb-1 gap-2">
        <div>
          <h5 class="text-primary fw-bold mb-0">{{ card.front }}</h5>
          <small class="text-muted">
            {{ card.payload.ipa }}
            <span v-if="card.payload.pos" class="badge bg-light text-dark ms-1">{{ card.payload.pos }}</span>
            <span v-if="card.source === 'ai'" class="badge bg-info-subtle text-info-emphasis ms-1" title="Generated by AI">AI</span>
          </small>
        </div>
        <div class="d-flex gap-1 flex-shrink-0">
          <a v-if="isEnglish" :href="youglishUrl" target="_blank" rel="noopener" class="btn btn-outline-info btn-sm" title="Hear it in real videos (YouGlish)">
            <i class="bi bi-play-circle"></i>
          </a>
          <button v-if="isEnglish" @click="$emit('speak', card.front)" class="btn btn-outline-secondary btn-sm" title="Listen">
            <i class="bi bi-volume-up"></i>
          </button>
          <button v-if="canDelete" @click="$emit('remove')" class="btn btn-outline-danger btn-sm" title="Delete card (admin)">
            <i class="bi bi-trash"></i>
          </button>
        </div>
      </div>

      <CardDetails :card="card" :speakable="isEnglish" class="mt-2"
        @speak="(en: string, vi?: string) => $emit('speakSentence', en, vi)" />
    </div>
    <div class="card-footer bg-white border-0 pt-0 d-flex justify-content-between align-items-center">
      <small class="text-muted">{{ status }}</small>
      <button v-if="!card.progress" @click="$emit('add')" class="btn btn-success btn-sm">
        <i class="bi bi-plus-circle"></i> Learn
      </button>
      <span v-else class="badge" :class="card.progress.suspended ? 'bg-secondary' : 'bg-success-subtle text-success-emphasis'">
        <i class="bi bi-check2"></i> In your list
      </span>
    </div>
  </div>
</template>

<script setup lang="ts">
import { computed } from 'vue'
import CardDetails from '../CardDetails.vue'
import type { CardWithProgress } from '../../types'
import { stateLabel } from '../../types'

const props = defineProps<{ card: CardWithProgress; canDelete?: boolean }>()
defineEmits<{ speak: [text: string]; speakSentence: [en: string, vi?: string]; add: []; remove: [] }>()

const isEnglish = computed(() => props.card.kind === 'vocab' || props.card.kind === 'phrasal')
const youglishUrl = computed(() => `https://youglish.com/pronounce/${encodeURIComponent(props.card.front)}/english`)
const status = computed(() => {
  const p = props.card.progress
  if (!p) return ''
  const label = stateLabel(p)
  if (p.state === 0 || p.suspended) return label
  return `${label} · next ${new Date(p.due).toLocaleDateString()}`
})
</script>
